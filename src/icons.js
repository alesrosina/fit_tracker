// Rasterizes an icon to an <img> in the given fill colour, for drawing on a
// <canvas> (week chart, share card) where Vue components can't render.
const imageCache = new Map()
export function iconImage(name, color, size = 48) {
    const key = `${name}|${color}|${size}`
    if (imageCache.has(key)) return imageCache.get(key)
    const svg = (icons[name] ?? icons.exercise)
        .replace(/width="\d+"/, `width="${size}"`)
        .replace(/height="\d+"/, `height="${size}"`)
        .replace('<svg ', `<svg fill="${color}" `)
    const promise = new Promise(resolve => {
        const img = new Image()
        img.onload = () => resolve(img)
        img.onerror = () => resolve(null)
        img.src = 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(svg)
    })
    imageCache.set(key, promise)
    return promise
}
